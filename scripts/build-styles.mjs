// scripts/build-styles.mjs
// 从一个内容 JSON 生成新风格所需的全部产物，避免手改 6 处：
//   styles/{id}.html            详情页
//   card-styles/{id}-card.css   首页卡片样式
//   style.css 里的 body.theme-{id} 主题块（标记式，可重复执行）
//   zips/{id}.zip               可运行的单页包（预览页 + 内联 CSS）
//
// 依赖 previews/{id}.html 与 previews/{id}.css 已由 build-previews.mjs 生成。

import fs from 'node:fs';
import { Report, assertClean, validateNewStyles } from './lib/validate.mjs';
import path from 'node:path';
import { BRAND } from './lib/seo.mjs';
import { execSync } from 'node:child_process';

const ROOT = process.cwd();
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const write = (p, s) => fs.writeFileSync(path.join(ROOT, p), s);
const exists = (p) => fs.existsSync(path.join(ROOT, p));

const styles = JSON.parse(read('data/new-styles.json'));

// 数据守卫：themeCss 必须真的以 body.theme-{id} 开头，cardCss 必须选中自己的卡
{
    const rep = new Report('new-styles');
    validateNewStyles(styles, rep);
    assertClean(rep);
}


const esc = (s) =>
    String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const arrow = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16" aria-hidden="true"><path d="M7.78 12.53a.75.75 0 0 1-1.06 0l-4.25-4.25a.75.75 0 0 1 0-1.06l4.25-4.25a.751.751 0 0 1 1.06 1.06L4.81 8l2.97 2.97a.75.75 0 0 1 0 1.06Z"/><path d="M13.25 8A.75.75 0 0 1 12.5 8.75H4.5a.75.75 0 0 1 0-1.5h8a.75.75 0 0 1 .75.75Z"/></svg>`;

function detailPage(s) {
    const features = s.features
        .map((f) => `                <li><strong>${esc(f.title)}:</strong> ${esc(f.detail)}</li>`)
        .join('\n');
    const paras = s.longDescription.map((p) => `            <p>${esc(p)}</p>`).join('\n');
    const whenUse = s.whenToUse.map((t) => `                <li>${esc(t)}</li>`).join('\n');
    const whenNot = s.whenNot.map((t) => `                <li>${esc(t)}</li>`).join('\n');
    const tokens = s.tokens.map((t) => `<span class="token-chip">${esc(t)}</span>`).join('\n            ');

    return `<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${esc(s.name)} — Style Detail, Prompt and CSS</title>
    <link rel="preconnect" href="https://fonts.googleapis.com">
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
    <link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;600&family=Roboto+Mono&display=swap" rel="stylesheet">
    <link rel="stylesheet" href="../style.css">
</head>
<body class="theme-${s.id}">
    <header>
        <div class="container">
            <h1>${esc(s.name)}</h1>
            <p>${esc(s.tagline)}</p>
        </div>
    </header>

    <main class="container style-detail-container">

        <a href="index.html" class="back-link">
            ${arrow}
            <span>Back to Style List</span>
        </a>

        <section class="style-detail-section style-description">
            <h2>About This Style</h2>
${paras}

            <div class="token-row">
            ${tokens}
            </div>

            <h3>Main Features:</h3>
            <ul>
${features}
            </ul>
        </section>

        <section class="style-detail-section style-prompt">
            <h2>Example AI Prompt</h2>
            <pre tabindex="0" role="region" aria-label="Example AI prompt, scrollable code block"><code>${esc(s.prompt)}</code></pre>
        </section>

        <section class="style-detail-section style-css">
            <h2>Theme CSS Snippets</h2>
            <p>${esc(s.cssNote)}</p>
            <pre tabindex="0" role="region" aria-label="Theme CSS variables, scrollable code block"><code>${esc(s.themeCss)}</code></pre>
        </section>

        <section class="style-detail-section style-fit">
            <h2>Where it fits</h2>
            <div class="fit-grid">
                <div>
                    <h3>Use it when</h3>
                    <ul>
${whenUse}
                    </ul>
                </div>
                <div>
                    <h3>Avoid it when</h3>
                    <ul>
${whenNot}
                    </ul>
                </div>
            </div>
        </section>

        <section class="style-detail-section style-download">
            <h2>Resource Download</h2>
            <p>A working single-page demo in this style — the HTML and one self-contained stylesheet, no build step.</p>
            <a href="../zips/${s.id}.zip" class="btn btn-download" download>Download ${s.id}.zip</a>
        </section>

    </main>

    <footer>
        <div class="container">
            <p>&copy; <span id="current-year"></span> ${BRAND}</p>
        </div>
    </footer>
    <script src="../script.js" defer></script>
</body>
</html>
`;
}

function themeBlock(s) {
    // themeCss 已经是完整的 body.theme-{id} { ... } 规则
    return `/* build:theme:${s.id} */
/* ${s.name} — generated by scripts/build-styles.mjs */
${s.themeCss}
/* /build:theme:${s.id} */`;
}

function upsertTheme(s) {
    let css = read('style.css');
    const block = themeBlock(s);
    const re = new RegExp(
        `/\\* build:theme:${s.id} \\*/[\\s\\S]*?/\\* /build:theme:${s.id} \\*/`
    );
    if (re.test(css)) {
        css = css.replace(re, block);
    } else {
        css = css.trimEnd() + '\n\n' + block + '\n';
    }
    write('style.css', css);
}

function buildZip(s) {
    const tmp = `.tmp_zip_${s.id}`;
    const dir = path.join(ROOT, tmp, s.id);
    fs.rmSync(path.join(ROOT, tmp), { recursive: true, force: true });
    fs.mkdirSync(dir, { recursive: true });

    // 单页包 = 预览页 + 内联后的样式表，保证离线双击可看
    const base = exists('previews/_base.css') ? read('previews/_base.css') : '';
    const own = read(`previews/${s.id}.css`);
    let html = read(`previews/${s.id}.html`);
    html = html
        .replace(/[ \t]*<link rel="stylesheet" href="_base\.css">\n?/, '')
        .replace(
            new RegExp(`[ \\t]*<link rel="stylesheet" href="${s.id}\\.css">`),
            `    <link rel="stylesheet" href="${s.id}-standalone.css">`
        )
        .replace(/href="\.\.\/styles\/([a-z0-9-]+)\.html"/, 'href="#"')
        .replace(/<a class="back-chip"[^>]*>[\s\S]*?<\/a>/, '');

    write(path.join(tmp, s.id, 'index.html'), html);
    write(
        path.join(tmp, s.id, `${s.id}-standalone.css`),
        `/* ${s.name} — standalone stylesheet */\n\n${base}\n\n${own}`
    );
    fs.mkdirSync(path.join(ROOT, 'zips'), { recursive: true });
    // 必须先进临时目录再打包，否则压缩包里会带上临时目录前缀
    execSync(`cd "${path.join(ROOT, tmp)}" && zip -rq "${path.join(ROOT, 'zips', s.id + '.zip')}" "${s.id}"`, {
        stdio: 'pipe',
    });
    fs.rmSync(path.join(ROOT, tmp), { recursive: true, force: true });
}

let made = 0;
for (const s of styles) {
    if (!exists(`previews/${s.id}.css`)) {
        console.warn(`跳过（缺预览样式）: previews/${s.id}.css`);
        continue;
    }
    write(`styles/${s.id}.html`, detailPage(s));
    write(`card-styles/${s.id}-card.css`, s.cardCss.trimEnd() + '\n');
    upsertTheme(s);
    buildZip(s);
    made++;
}

console.log(`✓ 生成风格：${made} 个（详情页 + 卡片样式 + 主题块 + 下载包）`);
